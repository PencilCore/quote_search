def write_json(path: pathlib.Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"  {path.relative_to(ROOT)}  {path.stat().st_size:>8} bytes")


def split_sentences(s: str):
    parts = re.split(r"[。！？；]", s)
    return [p.strip() for p in parts if p.strip()]


def book(osis, zh, en, abbr, chapters=1, testament="X", zht=None):
    return {"osis": osis, "zh": zh, "zht": zht or zh, "en": en,
            "abbr": abbr, "testament": testament, "chapters": chapters}


